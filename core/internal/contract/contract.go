// Package contract generates the CLI's machine-readable contract from code:
//
//	contracts/cli.yaml                every command, its arguments, flags and JSON output schema
//	contracts/cli/<command>.schema.json  JSON Schema of each command's --json output
//	contracts/settings.schema.json    every setting, from the settings registry
//	contracts/run-status.schema.json  the run-status file frontends watch
//	contracts/notifications.schema.json  the notifications file frontends deliver
//	contracts/openapi.yaml            every type a frontend reads (run status and each
//	                                  --json output) as OpenAPI components, for generating
//	                                  frontend types (automator-ui does at build time)
//
// Go doc comments on the types become schema descriptions.
//
// The generated files are committed; a test fails when they're out of date
// (regenerate with `make contracts`).
package contract

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	gopath "path"
	"path/filepath"
	"reflect"
	"runtime"
	"sort"
	"strings"

	"github.com/invopop/jsonschema"
	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
	"go.yaml.in/yaml/v3"

	"github.com/BorysSerbyn/process-automator/core/internal/cli"
	"github.com/BorysSerbyn/process-automator/core/internal/notifications"
	"github.com/BorysSerbyn/process-automator/core/internal/runstatus"
	"github.com/BorysSerbyn/process-automator/core/internal/settings"
)

const header = "# GENERATED by `make contracts` from core/. Do not edit.\n"

// Generate returns every contract file, keyed by path relative to contracts/.
func Generate() (map[string][]byte, error) {
	files := map[string][]byte{}
	root := cli.NewRoot(nil) // the command tree doesn't depend on plugins
	outputs := cli.JSONOutputs(root)

	ref, err := commandReference(root, outputs)
	if err != nil {
		return nil, err
	}
	files["cli.yaml"] = ref

	comments, err := goComments()
	if err != nil {
		return nil, err
	}
	for path, v := range outputs {
		b, err := outputSchema(path, v, comments)
		if err != nil {
			return nil, err
		}
		files["cli/"+schemaName(path)] = b
	}
	if files["run-status.schema.json"], err = runStatusSchema(comments); err != nil {
		return nil, err
	}
	if files["notifications.schema.json"], err = notificationsSchema(comments); err != nil {
		return nil, err
	}
	if files["openapi.yaml"], err = openAPI(comments, outputs); err != nil {
		return nil, err
	}

	s, err := settingsSchema()
	if err != nil {
		return nil, err
	}
	files["settings.schema.json"] = s
	return files, nil
}

func schemaName(commandPath string) string {
	return strings.ReplaceAll(commandPath, " ", "-") + ".schema.json"
}

// --- command reference -------------------------------------------------------

type commandDoc struct {
	Command    string    `yaml:"command"`
	Usage      string    `yaml:"usage"`
	Summary    string    `yaml:"summary"`
	Example    string    `yaml:"example,omitempty"`
	Flags      []flagDoc `yaml:"flags,omitempty"`
	JSONOutput string    `yaml:"jsonOutput,omitempty"`
}

type flagDoc struct {
	Name    string `yaml:"name"`
	Type    string `yaml:"type"`
	Default string `yaml:"default,omitempty"`
	Usage   string `yaml:"usage"`
}

type reference struct {
	Binary      string       `yaml:"binary"`
	GlobalFlags []flagDoc    `yaml:"globalFlags"`
	Commands    []commandDoc `yaml:"commands"`
}

func commandReference(root *cobra.Command, outputs map[string]any) ([]byte, error) {
	ref := reference{Binary: root.Name(), GlobalFlags: flags(root.PersistentFlags())}
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if c.Hidden || c.Name() == "help" || c.Name() == "completion" {
			return
		}
		if c.Runnable() && c != root {
			path := strings.TrimPrefix(c.CommandPath(), root.Name()+" ")
			doc := commandDoc{
				Command: path,
				Usage:   c.UseLine(),
				Summary: c.Short,
				Example: dedent(c.Example),
				Flags:   commandFlags(c, root),
			}
			if _, ok := outputs[path]; ok {
				doc.JSONOutput = "cli/" + schemaName(path)
			}
			ref.Commands = append(ref.Commands, doc)
		}
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
	sort.Slice(ref.Commands, func(i, j int) bool { return ref.Commands[i].Command < ref.Commands[j].Command })

	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(ref); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// dedent trims each line of a cobra example (they're conventionally indented).
func dedent(s string) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	for i, l := range lines {
		lines[i] = strings.TrimSpace(l)
	}
	return strings.Join(lines, "\n")
}

// commandFlags is the command's own flags plus flags inherited from parents
// other than the root (the root's are documented once as globalFlags).
func commandFlags(c, root *cobra.Command) []flagDoc {
	fs := pflag.NewFlagSet(c.Name(), pflag.ContinueOnError)
	fs.AddFlagSet(c.NonInheritedFlags())
	c.InheritedFlags().VisitAll(func(f *pflag.Flag) {
		if root.PersistentFlags().Lookup(f.Name) == nil {
			fs.AddFlag(f)
		}
	})
	return flags(fs)
}

func flags(fs *pflag.FlagSet) []flagDoc {
	var out []flagDoc
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		d := flagDoc{Name: "--" + f.Name, Type: f.Value.Type(), Usage: f.Usage}
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" {
			d.Default = f.DefValue
		}
		out = append(out, d)
	})
	return out
}

// --- output schemas ----------------------------------------------------------

func outputSchema(commandPath string, v any, comments map[string]string) ([]byte, error) {
	r := &jsonschema.Reflector{ExpandedStruct: true, DoNotReference: true, CommentMap: comments, Mapper: enums}
	s := r.Reflect(v)
	s.ID = jsonschema.ID(schemaName(commandPath))
	s.Title = "procauto " + commandPath + " --json"
	return marshal(s)
}

func runStatusSchema(comments map[string]string) ([]byte, error) {
	r := &jsonschema.Reflector{ExpandedStruct: true, DoNotReference: true, CommentMap: comments, Mapper: enums}
	s := r.Reflect(runstatus.Status{})
	s.ID = "run-status.schema.json"
	s.Title = "Run status"
	s.Description = "Written by the Go core, watched by frontends: " + s.Description
	return marshal(s)
}

func notificationsSchema(comments map[string]string) ([]byte, error) {
	r := &jsonschema.Reflector{ExpandedStruct: true, DoNotReference: true, CommentMap: comments, Mapper: enums}
	s := r.Reflect(notifications.File{})
	s.ID = "notifications.schema.json"
	s.Title = "Notifications"
	s.Description = "Written by the Go core, delivered by frontends: " + s.Description
	return marshal(s)
}

// --- OpenAPI components for frontends ----------------------------------------

// enums gives Go string types with a fixed set of values their enum, so
// frontends get them as types rather than bare strings.
func enums(t reflect.Type) *jsonschema.Schema {
	if t != reflect.TypeFor[settings.Type]() {
		return nil
	}
	s := &jsonschema.Schema{Type: "string"}
	for _, v := range settings.Types {
		s.Enum = append(s.Enum, string(v))
	}
	return s
}

// openAPI collects every type a frontend reads as named OpenAPI components:
// run status and each command's --json output (element type for lists).
func openAPI(comments map[string]string, outputs map[string]any) ([]byte, error) {
	r := &jsonschema.Reflector{CommentMap: comments, Namer: componentName, Mapper: enums}
	schemas := map[string]any{}
	add := func(v any) error {
		t := reflect.TypeOf(v)
		for t.Kind() == reflect.Slice {
			t = t.Elem()
		}
		s := r.ReflectFromType(t)
		for name, def := range s.Definitions {
			b, err := json.Marshal(def)
			if err != nil {
				return err
			}
			b = bytes.ReplaceAll(b, []byte(`"#/$defs/`), []byte(`"#/components/schemas/`))
			var m any
			if err := json.Unmarshal(b, &m); err != nil {
				return err
			}
			schemas[name] = openAPISchema(m)
		}
		return nil
	}
	if err := add(runstatus.Status{}); err != nil {
		return nil, err
	}
	if err := add(notifications.File{}); err != nil {
		return nil, err
	}
	if err := add(cli.ErrorOutput{}); err != nil {
		return nil, err
	}
	for _, v := range outputs {
		if err := add(v); err != nil {
			return nil, err
		}
	}
	doc := map[string]any{
		"openapi":    "3.1.0",
		"info":       map[string]any{"title": "procauto frontend types", "version": "1"},
		"paths":      map[string]any{},
		"components": map[string]any{"schemas": schemas},
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// openAPISchema rewrites JSON Schema's boolean "any value" schema (`true`, as
// reflected from Go `any`) to `{}`, which OpenAPI tooling understands.
func openAPISchema(v any) any {
	m, ok := v.(map[string]any)
	if !ok {
		return v
	}
	if props, ok := m["properties"].(map[string]any); ok {
		for name, p := range props {
			if p == true {
				props[name] = map[string]any{}
			} else {
				props[name] = openAPISchema(p)
			}
		}
	}
	if items, ok := m["items"]; ok {
		if items == true {
			m["items"] = map[string]any{}
		} else {
			m["items"] = openAPISchema(items)
		}
	}
	return m
}

// componentName prefixes run-status types so their names read on their own
// (runstatus.Status → RunStatus, runstatus.Run → RunStatusRun), and keep
// those of types that moved package (loginitems.Status → LoginItemsOutput).
func componentName(t reflect.Type) string {
	if strings.HasSuffix(t.PkgPath(), "/runstatus") {
		return "RunStatus" + strings.TrimPrefix(t.Name(), "Status")
	}
	if strings.HasSuffix(t.PkgPath(), "/notifications") && t.Name() == "File" {
		return "NotificationsFile"
	}
	if strings.HasSuffix(t.PkgPath(), "/loginitems") && t.Name() == "Status" {
		return "LoginItemsOutput"
	}
	return t.Name()
}

// goComments reads the Go doc comments of the engine's packages, so schemas
// carry the same descriptions as the code. Works from any working directory
// inside core/ (make runs it from core/, tests from their package).
func goComments() (map[string]string, error) {
	_, file, _, _ := runtime.Caller(0)
	core := filepath.Join(filepath.Dir(file), "..", "..")
	cwd, err := os.Getwd()
	if err != nil {
		return nil, err
	}
	relCwd, err := filepath.Rel(core, cwd)
	if err != nil {
		return nil, err
	}
	relInternal, err := filepath.Rel(cwd, filepath.Join(core, "internal"))
	if err != nil {
		return nil, err
	}
	const module = "github.com/BorysSerbyn/process-automator/core"
	r := &jsonschema.Reflector{}
	if err := r.AddGoComments(gopath.Join(module, filepath.ToSlash(relCwd)), relInternal); err != nil {
		return nil, err
	}
	return r.CommentMap, nil
}

// --- settings schema ---------------------------------------------------------

func settingsSchema() ([]byte, error) {
	props := map[string]any{}
	keys := make([]string, 0, len(settings.Registry))
	for _, s := range settings.Registry {
		keys = append(keys, s.Key)
		props[s.Key] = settingSchema(s)
	}
	// Per-routine settings: one set per routine file on the device, so they're
	// patterns. Generated from settings.RoutineFields.
	patterns := map[string]any{}
	for _, f := range settings.RoutineFields {
		p := settingSchema(settings.Setting{
			Type: f.Type, Default: f.Default, Unit: f.Unit, Enum: f.Enum, Min: f.Min, Max: f.Max,
			Description: f.Description + " Defaults to `automator." + f.Name + "` in the routine's file.",
		})
		if f.ScheduledOnly {
			p["x-scheduledOnly"] = true
		}
		patterns[`^routines\.[a-z0-9][a-z0-9-]*\.`+f.Name+`$`] = p
	}
	patterns[`^routines\.[a-z0-9][a-z0-9-]*\.params\.[a-z][a-z0-9_]*$`] = map[string]any{
		"x-type":      "parameter",
		"description": "A routine parameter's value (declared in its file's automator.parameters, with its type and default; required ones have no default).",
	}
	doc := map[string]any{
		"$schema":              "https://json-schema.org/draft/2020-12/schema",
		"$id":                  "settings.schema.json",
		"title":                "procauto settings",
		"description":          "Generated from core/internal/settings. Values live under `settings:` in the config file; change them with `procauto settings set <key> <value>`.",
		"type":                 "object",
		"additionalProperties": false,
		"properties":           props,
		"patternProperties":    patterns,
		"x-order":              keys,
	}
	return marshal(doc)
}

// settingSchema is one setting's JSON Schema.
func settingSchema(s settings.Setting) map[string]any {
	p := map[string]any{
		"description": s.Description,
		"x-type":      string(s.Type),
	}
	if s.Default != nil {
		p["default"] = s.Default
	}
	if s.Unit != "" {
		p["x-unit"] = s.Unit
	}
	if s.NotImplemented {
		p["x-notImplemented"] = true
	}
	switch s.Type {
	case settings.TypeBool:
		p["type"] = "boolean"
	case settings.TypeInt:
		p["type"] = "integer"
	case settings.TypeNumber, settings.TypePercent:
		p["type"] = "number"
	case settings.TypeEnum:
		p["type"] = "string"
		p["enum"] = s.Enum
	case settings.TypeList:
		items := map[string]any{"type": "string"}
		if len(s.Enum) > 0 {
			items["enum"] = s.Enum
		}
		p["type"], p["items"] = "array", items
	default:
		p["type"] = "string"
	}
	if s.Min != nil {
		p["minimum"] = *s.Min
	}
	if s.Max != nil {
		p["maximum"] = *s.Max
	}
	return p
}

func marshal(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, fmt.Errorf("marshal contract: %w", err)
	}
	return buf.Bytes(), nil
}
